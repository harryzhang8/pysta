//==========================================================================
// 例 4（RTL）：输入端口 -> 输出端口（纯组合逻辑）
//--------------------------------------------------------------------------
// 中间一个寄存器都没有，路径从输入端口 C 一直走到输出端口 D。
// 这类路径不靠 create_clock 约束，而靠两端的
// set_input_delay / set_output_delay（或直接 set_max_delay）夹出来。
//
// 预期结果：Tm = Tclk - input_delay - output_delay = 20 - 0.4 - 0.8 = 18.8ns
//==========================================================================
module ex4_in2out (
  input  wire clk,      // 仅为定义约束参考时钟而存在，本模块逻辑不用它
  input  wire C,
  output wire D
);

  // 组合逻辑 M
  wire n1 = ~C;
  wire n2 = n1 ^ C;
  wire d  = n2 | C;

  assign D = d;

endmodule
