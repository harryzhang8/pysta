//==========================================================================
// 例 5（RTL）：多时钟 —— 输入端口
//--------------------------------------------------------------------------
// 设计内部只有 clkb 一个时钟；数据 A 来自上游 clka 时钟域。
// clka 在本设计里没有端口，所以 SDC 里要用**虚拟时钟**定义它。
//
// 预期结果：公共基本周期 LCM(30,20) = 60ns，
//           clka@0 -> clkb@20 与 clka@30 -> clkb@40 取最严格，
//           => 留给输入逻辑只有 10 - 5.5 - Tsu = 3.5ns
//==========================================================================
module ex5_multi_clk_in (
  input  wire clkb,
  input  wire A,
  output wire Q
);

  // 输入组合逻辑 N
  wire n1 = ~A;
  wire n2 =  n1;

  reg q;

  always @(posedge clkb) begin
    q <= n2;
  end

  assign Q = q;

endmodule
