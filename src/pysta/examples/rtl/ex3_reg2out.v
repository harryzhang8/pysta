//==========================================================================
// 例 3（RTL）：寄存器的 CP 端口 -> 输出端口
//--------------------------------------------------------------------------
// 组合逻辑在这里被实现成"反相 + 缓冲"（综合工具做驱动能力优化时
// 会在输出端口前面插缓冲器，这是很常见的形态）。
//
// 预期结果：组合逻辑最大延时 = 20 - 5.4 - 1 - 1 = 12.6ns
//==========================================================================
module ex3_reg2out (
  input  wire clk,
  input  wire D1,
  output wire B
);

  reg q1;

  always @(posedge clk) begin
    q1 <= D1;
  end

  // 组合逻辑 M
  wire n1 = ~q1;
  wire b  =  n1;

  assign B = b;

endmodule
