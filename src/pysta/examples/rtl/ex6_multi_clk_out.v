//==========================================================================
// 例 6（RTL）：多时钟 —— 输出端口
//--------------------------------------------------------------------------
// 设计内部只有 clkb；输出端口 B 送出去后被 clkc(75MHz) 和 clkd(100MHz)
// 两个外部器件接收。这两个时钟在本设计里也没有端口，同样要建虚拟时钟。
//
// 预期结果：
//     对 clkd：预算 = 10 - 4.5 - Tco
//     对 clkc：预算 = 40/3 - 2.5 - Tco  （40/3 = 13.333，即 6.667 的精确值）
//   取最严格 => 预算 = 40/3 - 2.5 - Tco = 3.1667ns
//==========================================================================
module ex6_multi_clk_out (
  input  wire clkb,
  input  wire D1,
  output wire B
);

  reg q1;

  always @(posedge clkb) begin
    q1 <= D1;
  end

  // 输出组合逻辑 S
  wire n1 = ~q1;
  wire b  =  n1;

  assign B = b;

endmodule
