//==========================================================================
// 例 2（RTL）：输入端口 -> 寄存器的 D 端口
//--------------------------------------------------------------------------
// 说明：只有一个输入端口时，任意组合逻辑最终只能退化成该信号本身或其反。
//       这没关系 —— 本例的要点是"用 set_input_delay 把外部延时告诉工具"，
//       组合逻辑的功能完全不重要，重要的是它的**延时**。
//
// 预期结果：内部逻辑最大延时 = 20 - 7.4 - 1 = 11.6ns
//==========================================================================
module ex2_in2reg (
  input  wire clk,
  input  wire A,
  output wire Q2
);

  // 逻辑 N：三级门 (NAND2 -> INV -> AND2)
  wire n1 = ~(A & A);        // NAND2X1
  wire n2 = ~n1;             // INVX1
  wire n3 = n2 & A;          // AND2X1

  reg q2;

  always @(posedge clk) begin
    q2 <= n3;
  end

  assign Q2 = q2;

endmodule
