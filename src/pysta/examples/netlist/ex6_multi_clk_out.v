//==========================================================================
// 例 6：多时钟 —— 输出端口
//--------------------------------------------------------------------------
// 场景：
//   本设计内部只有一个时钟 clkb（周期 20ns，有对应端口）。
//   输出端口 B 送出去以后，会被两个不同频率的外部器件接收：
//       clkc = 300MHz/4 = 75MHz  -> 周期 13.333ns（精确值 40/3 ns）
//       clkd = 100MHz            -> 周期 10ns
//   这两个时钟在设计里没有端口，同样要建成**虚拟时钟**。
//
// 预期结果：
//     对 clkd：预算 = 10 - 4.5 - Tco
//     对 clkc：预算 = 40/3 - 2.5 - Tco
//   取最严格 => 40/3 - 2.5 - Tco = 3.1667 - Tco
//   （40/3 ≈ 13.333，对 clkb 在 20ns 发出、clkc 在 80/3 = 26.667ns 捕获）
//
// 注意 set_output_delay 的第二条必须带 -add_delay，否则会把第一条覆盖掉。
//==========================================================================
module ex6_multi_clk_out (
  clkb,
  D1,
  B
);

  input  clkb;     // 本设计唯一的真实时钟
  input  D1;
  output B;        // 需要同时满足 clkc / clkd 两个接收时钟的端口

  wire q1;
  wire n1;

  // 末级寄存器
  DFFRQ FF1 (.CP(clkb), .D(D1), .Q(q1));

  // 输出组合逻辑 S
  INVX1 U1 (.A(q1), .Y(n1));
  BUFX1 U2 (.A(n1), .Y(B));

endmodule
