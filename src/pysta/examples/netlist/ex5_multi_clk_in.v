//==========================================================================
// 例 5：多时钟 —— 输入端口
//--------------------------------------------------------------------------
// 场景：
//   上游器件用 clka（周期 30ns，分频而来）；本设计内部只用 clkb（周期 20ns）。
//   clka 在本设计里没有对应端口，所以要用**虚拟时钟**来定义它。
//
// 预期结果（关键！）：
//   clka 在 0ns 发数据  -> clkb 在 20ns 捕获，留给输入逻辑 20-5.5-Tsu；
//   clka 在 30ns 又发数据 -> clkb 在 40ns 捕获，留给输入逻辑 10-5.5-Tsu；
//   两条必须同时满足，取最严格的那条 => 10 - 5.5 - Tsu。
//
// 这里 30/20 的公共基本周期是 60ns，STA 会把 0ns 和 30ns 两个发送沿
// 都遍历一遍再取最差，自动得到这个结论。
//==========================================================================
module ex5_multi_clk_in (
  clkb,
  A,
  Q
);

  input  clkb;     // 本设计唯一的真实时钟
  input  A;        // 上游 clka 时钟域送进来的数据
  output Q;

  wire n1;
  wire n2;

  // 输入组合逻辑 N
  INVX1  U1 (.A(A),  .Y(n1));
  BUFX1  U2 (.A(n1), .Y(n2));

  // clkb 域的捕获寄存器
  DFFRQ  FF2 (.CP(clkb), .D(n2), .Q(Q));

endmodule
