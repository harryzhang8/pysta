//==========================================================================
// 例 8：时序例外 —— 逻辑伪路径
//--------------------------------------------------------------------------
// 电路结构（两个 MUX 串起来，共用同一个选择信号 S）：
//
//        A ──┬──> MUX0.I0 ──┐
//            │              ├─> MUX0.Y ──┬──> MUX1.I0 ──┐
//            └──> MUX0.I1 ──┘            └──> MUX1.I1 ──┴─> MUX1.Y ──> B
//        S ──────> MUX0.S            S ──────> MUX1.S
//
// 分析：
//     S=0 时数据通路是 MUX0/I0 -> MUX1/I0；
//     S=1 时数据通路是 MUX0/I1 -> MUX1/I1。
//   无论 S 取何值，MUX0/I0 -> MUX1/I1 与 MUX0/I1 -> MUX1/I0 这两条交叉
//   通路都没有数据流通。它们在物理上存在连接、但在逻辑上不可能导通，
//   这就是所谓的**逻辑伪路径**，应当用 set_false_path 排除掉。
//==========================================================================
module ex8_pseudo_path (
  clk,
  A,
  S,
  B
);

  input  clk;      // 仅用于定义约束参考时钟
  input  A;        // 数据
  input  S;        // 两个 MUX 共用的选择信号
  output B;

  wire y0;
  wire y1;

  MUX2X1 MUX0 (.I0(A),  .I1(A),  .S(S), .Y(y0));
  MUX2X1 MUX1 (.I0(y0), .I1(y0), .S(S), .Y(y1));
  BUFX1  U3   (.A(y1),  .Y(B));

endmodule
