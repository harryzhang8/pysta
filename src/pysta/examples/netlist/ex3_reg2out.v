//==========================================================================
// 例 3：寄存器的 CP 端口 -> 输出端口
//--------------------------------------------------------------------------
// 电路模型：
//   时钟上升沿时内部寄存器 FF1 发出数据，经过要综合的组合逻辑，
//   到达输出端口 B，在下一个时钟上升沿被外部器件的 FF2 捕获。
//
// 参数：
//   时钟周期 20ns，外部电路延时 5.4ns，下游 FF2 建立时间 1ns，
//   FF1 翻转时间 Tco 1ns
//   =>  组合逻辑的最大延时 = 20 - 5.4 - 1 - 1 = 12.6ns
//   对应约束： set_output_delay -max 6.4 -clock clk [get_ports B]
//             （6.4 = 外部组合延时 5.4 + 下游 FF2 的 Tsu 1.0）
//==========================================================================
module ex3_reg2out (
  clk,
  D1,
  B
);

  input  clk;
  input  D1;       // FF1 的数据输入
  output B;        // 被约束的输出端口

  wire q1;         // FF1 输出
  wire n1;         // 逻辑 M 中间节点

  // 末级寄存器（路径起点是它的 CP 引脚）
  DFFRQ FF1 (.CP(clk), .D(D1), .Q(q1));

  // 要综合的组合逻辑 M
  INVX1 U1 (.A(q1), .Y(n1));
  BUFX1 U2 (.A(n1), .Y(B));

endmodule
