//==========================================================================
// 例 1：寄存器 -> 寄存器
//--------------------------------------------------------------------------
// 预期结果：
//     路径 N 的最大时延  TN <= Tclk - Tco - Tsu - Tuncertainty
//     只要 create_clock 定义了时钟，寄存器之间的路径就自动被约束了。
//
// 这里把"逻辑 N"具体化成 INVX1 + NAND2X1 两级门，
// 便于 STA 算出真实的组合延时并与预算比较。
//==========================================================================
module ex1_reg2reg (
  clk,
  dina,
  douta
);

  input  clk;      // 时钟
  input  dina;     // 一级寄存器的数据输入
  output douta;    // 二级寄存器的输出

  wire q1;         // FF1 输出
  wire n1;         // 逻辑 N 的中间节点
  wire n2;         // 逻辑 N 的输出 -> FF2/D

  // 起点的"寄存器CP端口"
  DFFRQ  FF1 (.CP(clk), .D(dina), .Q(q1));
  // 寄存器之间的组合逻辑 N
  INVX1  U1  (.A(q1),   .Y(n1));
  NAND2X1 U2 (.A(n1),   .B(dina), .Y(n2));
  // 终点的"寄存器D端口"
  DFFRQ  FF2 (.CP(clk), .D(n2),  .Q(douta));

endmodule
