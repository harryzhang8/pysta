//==========================================================================
// 例 2：输入端口 -> 寄存器的 D 端口
//--------------------------------------------------------------------------
// 电路模型：
//   上游器件里的 FF1 在时钟上升沿发数据，经过外部组合逻辑和线网，
//   到达本设计的输入端口 A；下一个时钟上升沿被内部 FF2 捕获。
//   需要被综合的是中间那段"逻辑"。
//
// 参数：
//   时钟周期 20ns，外部电路延时 7.4ns（含上游 FF1 的 Tco、组合逻辑与线网延时）
//   触发器建立时间 1ns  =>  内部逻辑最大延时 = 20 - 7.4 - 1 = 11.6ns
//
// 这里把"逻辑"实现成三级门：NAND2 -> INV -> AND2
//==========================================================================
module ex2_in2reg (
  clk,
  A,
  Q2
);

  input  clk;      // 内部时钟
  input  A;        // 来自外部器件的输入端口（被约束的起点）
  output Q2;       // 内部寄存器输出

  wire n1;         // 逻辑 N 第 1 级
  wire n2;         // 逻辑 N 第 2 级
  wire n3;         // 逻辑 N 第 3 级 -> FF2/D

  // 要综合的逻辑 N
  NAND2X1 U1 (.A(A),  .B(A),  .Y(n1));
  INVX1   U2 (.A(n1), .Y(n2));
  AND2X1  U3 (.A(n2), .B(A),  .Y(n3));

  // 本设计的捕获寄存器
  DFFRQ   FF2 (.CP(clk), .D(n3), .Q(Q2));

endmodule
