//==========================================================================
// 例 4：输入端口 -> 输出端口（纯组合逻辑）
//--------------------------------------------------------------------------
// 纯组合逻辑路径：输入端口 C 经过组合逻辑直接到输出端口 D，
// 中间没有任何寄存器。
//
// 预期结果：
//     组合逻辑的最大延时 Tm = Tclk - Tinput_delay - Toutput_delay
//     时钟周期 20ns 时：Tm = 20 - 0.4 - 0.8 = 18.8ns
//
// 注意：这条路径跨了"发送沿"和"捕获沿"两个时钟沿，
//       靠 set_input_delay / set_output_delay 一起把中间的组合逻辑夹住。
//==========================================================================
module ex4_in2out (
  clk,
  C,
  D
);

  input  clk;      // 仅为定义时钟而存在，组合路径本身不用它
  input  C;        // 起点：输入端口
  output D;        // 终点：输出端口

  wire n1;
  wire n2;

  // 组合逻辑 M
  INVX1  U1 (.A(C),  .Y(n1));
  XOR2X1 U2 (.A(n1), .B(C), .Y(n2));
  OR2X1  U3 (.A(n2), .B(C), .Y(D));

endmodule
